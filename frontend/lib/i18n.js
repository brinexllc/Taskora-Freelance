function cyrillic(text) {
  const pairs = {
    'o‘': 'ў',
    'g‘': 'ғ',
    sh: 'ш',
    ch: 'ч',
    yo: 'ё',
    yu: 'ю',
    ya: 'я',
    ts: 'ц',
  };
  const letters = {
    a: 'а',
    b: 'б',
    d: 'д',
    e: 'е',
    f: 'ф',
    g: 'г',
    h: 'ҳ',
    i: 'и',
    j: 'ж',
    k: 'к',
    l: 'л',
    m: 'м',
    n: 'н',
    o: 'о',
    p: 'п',
    q: 'қ',
    r: 'р',
    s: 'с',
    t: 'т',
    u: 'у',
    v: 'в',
    x: 'х',
    y: 'й',
    z: 'з',
    '’': 'ъ',
  };
  return text.replace(
    /Taskora|CLICK|ONEID|PAYME|UZS|SMS|Email|email|username|IT|MB|[OoGg]‘|[Ss][Hh]|[Cc][Hh]|[Yy][Ooua]|[Tt][Ss]|[A-Za-z’]/g,
    (part) => {
      if (
        /^(Taskora|CLICK|ONEID|PAYME|UZS|SMS|Email|email|username|IT|MB)$/.test(
          part,
        )
      )
        return part;
      const converted =
        pairs[part.toLowerCase()] || letters[part.toLowerCase()] || part;
      return part[0] === part[0].toUpperCase()
        ? converted[0].toUpperCase() + converted.slice(1)
        : converted;
    },
  );
}
